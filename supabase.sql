-- Run this entire script in Supabase > SQL Editor.
create table if not exists public.resources (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('derivations','formulas')),
  chapter integer not null check (chapter between 1 and 10),
  title text not null check (char_length(title) between 1 and 100),
  url text not null,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);

alter table public.resources enable row level security;

-- Everyone can read the public study library.
create policy "Public can read resources"
on public.resources for select
to anon, authenticated
using (true);

-- Only signed-in users can add resources. Create admin accounts yourself in Supabase.
create policy "Authenticated admins can add resources"
on public.resources for insert
to authenticated
with check (auth.uid() = created_by);

create policy "Authenticated admins can delete resources"
on public.resources for delete
to authenticated
using (auth.uid() = created_by);
